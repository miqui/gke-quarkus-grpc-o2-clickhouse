import { check, sleep } from 'k6';
import { randomIntBetween } from 'https://jslib.k6.io/k6-utils/1.4.0/index.js';
import { createAuthor, grpc, MESSAGES, rpc } from './k6-common.js';

export const options = {
  vus: __ENV.VUS ? parseInt(__ENV.VUS, 10) : 10,
  duration: __ENV.DURATION || '10s',
  thresholds: {
    checks: ['rate>0.99'],             // gRPC has no http_req_failed; every call is checked
    grpc_req_duration: ['p(95)<500'],  // 95% of calls below 500ms
  },
};

// Every message needs an author - create one shared author up front rather than one per iteration.
export function setup() {
  return { authorId: createAuthor('k6-create-messages') };
}

export default function (data) {
  const res = rpc(`${MESSAGES}/CreateMessage`, {
    title: `Load test message ${randomIntBetween(1, 1000000)}`,
    content: 'Generated by k6-create-messages.js',
    authorId: data.authorId,
  }, 'CreateMessage');

  check(res, {
    'status is OK': (r) => r.status === grpc.StatusOK,
    'response has id': (r) => !!(r.message && r.message.id),
  });

  // Simulate think time between 100ms and 300ms using k6-utils
  sleep(randomIntBetween(1, 3) * 0.1);
}
